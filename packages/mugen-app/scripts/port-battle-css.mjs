// THE ARTIFACT'S BATTLE STYLESHEET, SELECTED — NOT REWRITTEN.
//
// The App's battle screen is a reproduction of the Artifact's, and its
// look lives in ~2,000 lines of the Artifact's stylesheet mixed in with
// every other screen's. Retyping them would be a second stylesheet that
// drifts from the first on the first edit. So this reads the Artifact's
// CSS and keeps, rule for rule and byte for byte, exactly the parts the
// battle screen uses:
//
//   - every rule whose selector names a battle class (`bp-…`, `bx-…`),
//     including inside @media / @supports, which are kept around them;
//   - every @keyframes one of those rules animates with;
//   - the Artifact's design tokens, re-scoped from `:root` to
//     `.bp-screen` so they cannot recolour any other App screen (the two
//     palettes share names like --bg and --danger).
//
// Run `node scripts/port-battle-css.mjs` after the Artifact's battle
// styles change. `src/ui/battle/battleCss.test.ts` fails until you do.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const ARTIFACT_TOKENS = here('../../mugen-artifact/src/ui/styles/tokens.css');
const ARTIFACT_STYLES = here('../../mugen-artifact/src/ui/styles.css');
export const OUTPUT = here('../src/ui/battle/battle.generated.css');

/** A selector the battle screen draws with. */
const BATTLE_CLASS = /\.(bp|bx)-[\w-]+/;

function keepsBattle(rule) {
  return rule.type === 'rule' && BATTLE_CLASS.test(rule.selector);
}

/** Keyframe names used by any kept declaration. */
function animationNames(root) {
  const names = new Set();
  root.walkDecls(/^(animation|animation-name)$/, (decl) => {
    for (const part of decl.value.split(',')) {
      for (const word of part.trim().split(/\s+/)) {
        if (/^[a-zA-Z_][\w-]*$/.test(word)) names.add(word);
      }
    }
  });
  return names;
}

export function generate() {
  const styles = postcss.parse(readFileSync(ARTIFACT_STYLES, 'utf8'));
  const tokens = postcss.parse(readFileSync(ARTIFACT_TOKENS, 'utf8'));
  const out = postcss.root();

  // 1. The tokens, scoped to the battle screen.
  tokens.walkRules(':root', (rule) => {
    const scoped = rule.clone({ selector: '.bp-screen' });
    out.append(scoped);
  });
  // The Artifact's own stage size, which its landscape frame sets at
  // runtime and otherwise defaults to the viewport — as it does here.
  styles.walkRules(':root', (rule) => {
    const stage = rule.clone({ selector: '.bp-screen' });
    stage.nodes = stage.nodes.filter((n) => n.type === 'decl' && n.prop.startsWith('--stage-'));
    if (stage.nodes.length > 0) out.append(stage);
  });

  // 2. The battle rules, in source order, with their at-rule wrappers.
  const keptRules = postcss.root();
  for (const node of styles.nodes) {
    if (keepsBattle(node)) {
      keptRules.append(node.clone());
    } else if (node.type === 'atrule' && /^(media|supports)$/.test(node.name)) {
      const inner = node.clone({ nodes: [] });
      node.each((child) => {
        if (keepsBattle(child)) inner.append(child.clone());
      });
      if (inner.nodes.length > 0) keptRules.append(inner);
    }
  }

  // 3. The keyframes those rules use, wherever they were declared.
  const wanted = animationNames(keptRules);
  styles.walkAtRules('keyframes', (at) => {
    if (wanted.has(at.params)) out.append(at.clone());
  });

  out.append(keptRules.nodes);
  const header =
    '/* GENERATED by scripts/port-battle-css.mjs from the Artifact\'s\n' +
    '   styles.css and styles/tokens.css. Do not edit: edit the Artifact\n' +
    '   and regenerate. App-only adjustments live in battle.app.css. */\n';
  return header + out.toString().trim() + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generate());
  console.log(`wrote ${OUTPUT}`);
}
